import { CheckIcon, CodeIcon, CopyIcon } from "@phosphor-icons/react";
import { DynamicCodeBlock } from "fumadocs-ui/components/dynamic-codeblock";
import {
  useCodeUsage,
  useOperation,
  useResponseExamples,
} from "fumadocs-openapi/operation";
import { createOpenAPIPage } from "fumadocs-openapi/ui";
import { type ComponentProps, useEffect, useState } from "react";
import { referenceDocument } from "~/lib/openapi-ops";
import { usePyoAddress } from "~/lib/pyo-address";
import { withAddress } from "./PyoAddress";

/**
 * One page of the API reference, from Fumadocs' OpenAPI UI. The pages are
 * generated by `bun run sync-docs` from pyo-docs/openapi/pyo.json; the spec is
 * bundled as its own file and loaded once, when the first reference page opens.
 * Each page asks for a document derived from it (see openapi-ops).
 */
let spec: Promise<unknown> | undefined;
async function loadDocument(id: string) {
  spec ??= import("../../content/openapi/pyo.json").then((m) => m.default);
  const doc = referenceDocument(await spec, id);
  if (!doc) throw new Error(`No API reference document "${id}"`);
  return doc as never;
}

function CopyButton({ text }: { text: string }) {
  const [copied, setCopied] = useState(false);
  return (
    <button
      type="button"
      aria-label={copied ? "Copied" : "Copy"}
      onClick={async () => {
        await navigator.clipboard.writeText(text);
        setCopied(true);
        setTimeout(() => setCopied(false), 1500);
      }}
      className="api-card-icon-button"
    >
      {copied ? <CheckIcon size={14} /> : <CopyIcon size={14} />}
    </button>
  );
}

function Code({ lang, code }: { lang: string; code: string }) {
  return (
    <DynamicCodeBlock
      lang={lang}
      code={code}
      codeblock={{
        allowCopy: false,
        "data-line-numbers": true,
        className: "api-card-code",
      }}
    />
  );
}

const LANG_KEY = "pyo-api-lang";

/** The request sample: the operation's name, a language, and the code. */
function RequestCard() {
  const { method, title, codeUsages } = useOperation();
  const generators = Array.from(codeUsages.map());
  const [chosen, setChosen] = useState<string | null>(null);
  // The reader's language from last time, once the page has hydrated.
  useEffect(() => setChosen(localStorage.getItem(LANG_KEY)), []);
  const id =
    generators.find(([key]) => key === chosen)?.[0] ?? generators[0]?.[0];
  const code = useCodeUsage(id ?? "") ?? "";
  const host = usePyoAddress();
  if (!id) return null;
  const lang = generators.find(([key]) => key === id)?.[1].lang ?? "bash";
  return (
    <section className="api-card" aria-label="Example request">
      <header className="api-card-header">
        <span
          className="api-tile"
          data-method={method.toLowerCase()}
          aria-hidden
        >
          <CodeIcon size={12} weight="bold" />
        </span>
        <span className="api-card-title">{title}</span>
        <select
          aria-label="Language"
          value={id}
          onChange={(e) => {
            setChosen(e.target.value);
            localStorage.setItem(LANG_KEY, e.target.value);
          }}
          className="api-card-select"
        >
          {generators.map(([key, g]) => (
            <option key={key} value={key}>
              {g.label ?? g.lang}
            </option>
          ))}
        </select>
        <CopyButton text={withAddress(code, host)} />
      </header>
      <Code lang={lang} code={code} />
    </section>
  );
}

/** An example response, for the first successful status by default. */
function ResponseCard() {
  const tabs = useResponseExamples();
  const first = tabs.find((t) => t.code.startsWith("2")) ?? tabs[0];
  const [status, setStatus] = useState(first?.code);
  const tab = tabs.find((t) => t.code === status) ?? first;
  if (!tab) return null;
  const sample = tab.examples?.[0]?.sample;
  const text = sample === undefined ? "" : JSON.stringify(sample, null, 2);
  return (
    <section className="api-card" aria-label="Example response">
      <header className="api-card-header">
        {tabs.length > 1 ? (
          <select
            aria-label="Response status"
            value={tab.code}
            onChange={(e) => setStatus(e.target.value)}
            className="api-card-select api-card-select-start"
          >
            {tabs.map((t) => (
              <option key={t.code} value={t.code}>
                {t.code} example
              </option>
            ))}
          </select>
        ) : (
          <span className="api-card-title">{tab.code} example</span>
        )}
        <span className="flex-1" />
        {text ? <CopyButton text={text} /> : null}
      </header>
      {text ? (
        <div className="api-card-scroll">
          <Code lang="json" code={text} />
        </div>
      ) : (
        <p className="api-card-empty">
          {tab.response.description || "No response body."}
        </p>
      )}
    </section>
  );
}

const OpenAPIPage = createOpenAPIPage({
  loadDocument,
  showResponseSchema: true,
  // No "try it" panel: the slot shows the method and path alone.
  playground: { enabled: false },
  content: {
    // The examples sit in a column of their own, like most API references.
    renderAPIExampleLayout: () => (
      <div className="api-examples">
        <RequestCard />
        <ResponseCard />
      </div>
    ),
    renderOperationLayout: (slots) => (
      <div className="api-op">
        <div className="api-op-head">
          {slots.header}
          {slots.apiPlayground}
          {slots.description}
        </div>
        <aside className="api-op-aside">{slots.apiExample}</aside>
        <div className="api-op-body">
          {slots.authSchemes}
          {slots.parameters}
          {slots.body}
          {slots.responses}
          {slots.callbacks}
        </div>
      </div>
    ),
  },
});

type Props = Omit<ComponentProps<typeof OpenAPIPage>, "preloaded">;

/** The component generated pages call as `<OpenAPIPage document="…" … />`. */
export function ApiPage(props: Props) {
  return (
    <OpenAPIPage
      {...(props as ComponentProps<typeof OpenAPIPage>)}
      preloaded={{ docs: {} }}
    />
  );
}
